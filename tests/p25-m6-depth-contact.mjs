import {fitSpatialHoopBars} from '../src/design/rc/fitSpatialHoopBars.js';
import {jointBeamLayerProposal} from '../src/compute/product/jointBeamLayerProposal.js';
import {jointCageSpacingProposal} from '../src/compute/product/jointCageSpacingProposal.js';
import {practicalCommandFromRecord} from '../src/modeling/practicalInputContract.js';
import assert from 'node:assert/strict';
import {designContext} from './fixtures/p24/context.js';
import {mixedJointFixture} from './fixtures/p25/mixedJoint.js';
import {stageDesignInputCommand} from '../src/modeling/designInputCommands.js';
import {jointColumnDepthProposal} from '../src/compute/product/jointColumnDepthProposal.js';
import {evaluateRcJoint} from '../src/design/connection/rcJoint.js';
const evaluateProvidedJointHoopDetail=(m,j)=>evaluateRcJoint(m,j)['joint-hoop-detail'];
const ctx=designContext(),m=ctx.model;
try{
 for(const c of mixedJointFixture(m))stageDesignInputCommand(m,c,{},[]);
 assert.equal(fitSpatialHoopBars({}, {}, {transfer:'unknown'}).reason,'SPATIAL_FIT_SOURCE_MAPPING_REQUIRED');
 assert.equal(fitSpatialHoopBars({}, {}, {transfer:'section-resize'}).reason,'SPATIAL_FIT_SOURCE_MAPPING_REQUIRED');
 const joint=m.designDetails.connections[0],before=evaluateProvidedJointHoopDetail(m,joint);
 assert.equal(before.outerHoopSupport.status,'OK');
 const proposal=jointColumnDepthProposal(m,joint);assert.equal(proposal.ok,true,JSON.stringify(proposal));
 for(const c of proposal.additionalCommands)stageDesignInputCommand(m,c,{},[]);
 const after=evaluateProvidedJointHoopDetail(m,{...joint,...proposal.edits[0]});
 assert.equal(after.outerHoopSupport.status,'OK','section resizing must preserve certified hoop corner contacts');
 assert.deepEqual(after.outerHoopSupport.perimeterBarIndices,before.outerHoopSupport.perimeterBarIndices);
 const record={...joint,...proposal.edits[0]};
 const checks=Object.entries(evaluateRcJoint(m,record)).map(([checkId,c])=>({...c,checkId,entityId:'joint:B'}));
 const cage=jointCageSpacingProposal(practicalCommandFromRecord('connection-record',record),checks,m);
 assert.equal(cage.ok,true,JSON.stringify(cage));
 assert.equal(jointBeamLayerProposal(m,{...record,locked:true},checks).reason,'DETAIL_LOCKED');
 assert.equal(jointCageSpacingProposal({...practicalCommandFromRecord('connection-record',record),locked:true},checks,m).reason,'DETAIL_LOCKED');
 const layer=jointBeamLayerProposal(m,record,checks);
 assert.equal(layer.ok,true,JSON.stringify(layer));
 const cloned=structuredClone(m);
 for(const c of layer.additionalCommands)stageDesignInputCommand(cloned,c,{},[]);
 const final=evaluateRcJoint(cloned,{...record,...layer.edits[0]});
 assert.equal(final['joint-bar-congestion'].status,'OK',JSON.stringify({reason:final['joint-bar-congestion'].reason,pairs:final['joint-bar-congestion'].pairs,minimum:final['joint-bar-congestion'].minimum}));
 const phaseChecks=Object.entries(final).map(([checkId,c])=>({...c,checkId,entityId:'joint:B'}));
 const phase=jointCageSpacingProposal(practicalCommandFromRecord('connection-record',{...record,...layer.edits[0]}),phaseChecks,cloned);
 assert.equal(phase.ok,false,'bounded phase search must not qualify colliding geometry');
 assert.equal(phase.reason,'JOINT_CAGE_NO_QUALIFIED_LAYOUT');
 assert.ok(phase.trials.some(t=>t.status==='OK'&&t.hoopStatus==='NG'));
 assert.ok(phase.trials.length<=40);
 console.log('PASS joint column depth enlargement preserves real spatial corner contacts');
}finally{await ctx.dispose();}
