import assert from 'node:assert/strict';
import {createRcServiceWorkflow} from '../src/compute/product/rcServiceWorkflow.js';
import {createResourceBudget} from '../src/core/resourceBudget.js';
import {createWorkflowInputIdentity} from '../src/core/workflowIdentity.js';
import {createModel} from '../src/core/model.js';
import {stableHash} from '../src/core/stableHash.js';
import {RC_SERVICE_ITERATION_VERSION} from '../src/metadata/rcServicePolicy.js';
const identity=createWorkflowInputIdentity({model:createModel()});
const settings={stiffnessMode:'fully-cracked-elastic',comboIds:['S'],maxIterations:20,tolerance:1e-6,spatialTolerance:.001,maxRefinements:1};
const result={rcPolicyVersion:RC_SERVICE_ITERATION_VERSION,stiffnessMode:'fully-cracked-elastic',sourceModelHash:identity.modelHash,ok:false,converged:false,reason:'RC_SPATIAL_REFINEMENT_LIMIT',trace:[],globalMethodQualified:false,designTransferAllowed:false};
const id=`rc-iteration-${stableHash({inputHash:identity.inputHash,settings,version:RC_SERVICE_ITERATION_VERSION})}`;
const row={inputHash:identity.inputHash,inputIdentity:identity,settings,result,resultHash:stableHash(result)};
const wrap=record=>{const body={version:'p25-rc-service-state-v1',records:[[id,record]]};return {...body,checksum:stableHash(body)};};
const create=()=>createRcServiceWorkflow({bridge:{getWorkflowInputIdentity:()=>identity},budget:createResourceBudget()});
const good=create();assert.equal(good.restoreState(wrap(row)).count,1);good.dispose();
const different=structuredClone(row);different.settings.spatialTolerance=.02;
const bad=create();assert.throws(()=>bad.restoreState(wrap(different)),{code:'RC_CHECKPOINT_INVALID'});assert.equal(bad.context().iterations.length,0);bad.dispose();
const unbound=structuredClone(row);delete unbound.settings;
assert.throws(()=>create().restoreState(wrap(unbound)),{code:'RC_CHECKPOINT_INVALID'});
const falseConvergence=structuredClone(row);falseConvergence.result={...result,ok:true,converged:true,spatialConverged:false};falseConvergence.resultHash=stableHash(falseConvergence.result);
assert.throws(()=>create().restoreState(wrap(falseConvergence)),{code:'RC_CHECKPOINT_INVALID'});
console.log('PASS checkpoint policy binding rejects mismatched or missing current calculation settings');
