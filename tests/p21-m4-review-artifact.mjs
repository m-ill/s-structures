import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createModel } from '../src/core/model.js';
import { installIndexEngineBridge } from '../src/ui/indexBridge.js';
import { createReportSnapshot } from '../src/report/phase11/reportSnapshot.js';
const model=createModel();model.meta={projectId:'P21-REPORT'};
model.nodes=[{id:'N1',x:0,y:0,z:0,support:'fixed'},{id:'N2',x:0,y:0,z:3}];
model.members=[{id:'B',type:'frame',n1:'N1',n2:'N2',matId:'concrete',secId:'rcsq400',design:{role:'beam'}}];
model.loadCases=[{id:'D',type:'dead'}];model.loads=[{id:'H',type:'nodal',node:'N2',P:100,dir:'-x',case:'D'}];
model.loadCombinations=[{id:'U',name:'Strength',type:'strength',factors:{D:1.4}}];
model.analysisCases=[{id:'STATIC',kind:'static',settings:{comboId:'U',pDeltaMethod:'off'}}];
const target={model:()=>model,location:{search:''}},bridge=installIndexEngineBridge(target);
const good=r=>{assert.equal(r.ok,true,JSON.stringify(r));return r;};
const run=good(await bridge.runElasticWorkflow({plan:good(bridge.planElasticWorkflow({caseIds:['STATIC']})),requestId:'run'}));
const review=good(bridge.startDesignReview({plan:good(bridge.planDesignReview({sources:[{analysisRunId:run.steps[0].analysisRunId,comboId:'U'}]})),requestId:'review'}));
const {checks,messages,summary}=review.result;
assert.ok(checks.some(x=>x.status==='NG'));assert.ok(messages.length>0);
assert.equal(new Set(checks.map(x=>x.checkKey)).size,checks.length);
assert.equal(summary.counts.NG,checks.filter(x=>x.status==='NG').length);
assert.equal(summary.counts.N_A,2);
assert.ok(checks.filter(x=>x.status==='N_A').every(x=>x.ratio===null&&x.reason));
assert.ok(!checks.some(x=>messages.some(m=>m.code===x.checkId)),'explanatory messages must not become duplicate checks');
assert.equal(summary.checkCount,Object.values(summary.counts).reduce((a,b)=>a+b,0));
const report=good(bridge.createDesignReviewReport(review.designRunId));
assert.equal(report.snapshot.project.id,'P21-REPORT');
assert.equal(report.snapshot.analysis.maxDisplacement,review.result.sources[0].maxDisplacement);
assert.equal(report.snapshot.analysis.maxEquilibriumResidual,review.result.sources[0].equilibriumResidual);
assert.equal(report.designTransferAllowed,false);assert.equal(report.snapshot.provenance.buildBound,false);
for(const format of ['html','json','csv']) {
 let offset=0,content='',manifest;
 do {const part=good(bridge.getDesignReviewArtifact(review.designRunId,{format,offset}));
  assert.equal(part.offsetUnit,'UTF-16-code-unit');assert.ok(part.content.length<=12000);
  assert.equal(part.chunkSha256,createHash('sha256').update(part.content).digest('hex'));
  content+=part.content;offset=part.nextOffset;manifest=part;
 } while(offset!==null);
 assert.equal(content,format==='html'?report.reports['ko-KR'].html:report[format]);
 assert.equal(Buffer.byteLength(content),manifest.byteLength);
 assert.equal(createHash('sha256').update(content).digest('hex'),manifest.sha256);
 assert.ok(content.includes(report.reportSnapshotHash));
 assert.equal(bridge.getDesignReviewArtifact(review.designRunId,{format,offset:content.length+1}).code,'ARTIFACT_RANGE_INVALID');
}
model.nodes[1].z=4;assert.equal(bridge.getDesignReviewArtifact(review.designRunId,{format:'csv'}).stale,true);
const empty=createReportSnapshot(createModel(),{});assert.equal(empty.analysis.maxDisplacement,null);assert.equal(empty.analysis.maxEquilibriumResidual,null);
console.log(JSON.stringify({ok:true,counts:summary.counts,messageCount:messages.length,failedMembers:summary.failedMemberCount,artifacts:report.artifactManifest}));
