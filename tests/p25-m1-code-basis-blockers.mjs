import assert from 'node:assert/strict';
import {designCodeBasis} from '../src/metadata/designCodeBasis.js';
import {getKcscRuleSources} from '../src/metadata/kcscRuleSources.js';
import {formatDesignCodeBasis} from '../src/report/designCodeBasisFormat.js';
const ref={...getKcscRuleSources(['142050'])[0],clause:'4.4.2(3)'};
const result={status:'OK',codeReferences:[ref],methodReviewRequired:true};
const basis=designCodeBasis('rc-confinement',result);
assert.equal(basis.status,'NOT_ESTABLISHED');
assert.deepEqual(basis.blockers,['METHOD_REVIEW_REQUIRED']);
assert.match(formatDesignCodeBasis(basis),/METHOD_REVIEW_REQUIRED/);
assert.equal(designCodeBasis('rc-confinement',{...result,methodReviewRequired:false}).status,'CLAUSE_APPLIED');
const missing=designCodeBasis('rc-confinement',{status:'NOT_CHECKED',incomplete:true,locationCoverage:{complete:false}});
assert.deepEqual(missing.blockers,['CHECK_INCOMPLETE','LOCATION_COVERAGE_INCOMPLETE','CHECK_NOT_EVALUATED','CODE_REFERENCES_MISSING']);
assert.deepEqual(designCodeBasis('rc-confinement',{status:'OK',codeReferences:[{...ref,sha256:'invalid'}]}).blockers,['CODE_REFERENCE_NOT_VERIFIED']);
assert.equal(result.methodReviewRequired,true);
const direct=designCodeBasis('rc-stability',{status:'OK',method:'refined-direct-elastic-second-order',methodReviewRequired:true,codeReferences:[{...getKcscRuleSources(['142020'])[0],clause:'4.4.4'}]});
assert.ok(direct.reviewTargets.every(r=>!r.clause.includes('4.4.6')),JSON.stringify(direct.reviewTargets));
assert.ok(direct.reviewTargets.some(r=>r.clause.includes('4.4.4')));
const legacy=designCodeBasis('rc-stability',{status:'NOT_CHECKED'});
assert.ok(legacy.reviewTargets.some(r=>r.clause.includes('4.4.6')));
const appendixRef={...getKcscRuleSources(['142030'])[0],clause:'4.1.1 (Appendix)',documentPart:'appendix'};
const appendix=designCodeBasis('rc-serviceability',{status:'OK',methodReviewRequired:true,codeReferences:[appendixRef]});
assert.ok(appendix.reviewTargets.every(r=>r.documentPart==='appendix'),JSON.stringify(appendix.reviewTargets));
assert.equal(appendix.status,'NOT_ESTABLISHED');
console.log('PASS code basis exposes independent blockers without granting qualification');
