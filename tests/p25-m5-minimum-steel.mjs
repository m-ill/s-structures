import assert from 'node:assert/strict';
import {footingMinimumSteel} from '../src/design/foundation/footingMinimumSteel.js';
const x={width:2,thickness:.5,fy:400,area:.002,spacing:.15};
assert.equal(footingMinimumSteel(x).status,'OK');assert.equal(footingMinimumSteel(x).requiredArea,.002);
assert.equal(footingMinimumSteel({...x,area:.00199}).status,'NG');
assert.equal(footingMinimumSteel({...x,spacing:.451}).status,'NG');
assert.equal(footingMinimumSteel({...x,thickness:1}).requiredArea,.0036);
assert.ok(Math.abs(footingMinimumSteel({...x,fy:600}).requiredArea-.0014)<1e-12);
console.log('PASS uniform footing minimum area, thick-member cap and spacing');

const areaFailure=footingMinimumSteel({...x,area:.001});
assert.equal(areaFailure.reason,'FOOTING_MINIMUM_STEEL_AREA_INSUFFICIENT');
assert.deepEqual(areaFailure.failedCriteria,['minimum-area']);
assert.equal(areaFailure.criteria.find(c=>c.id==='minimum-area').provided,.001);
const spacingFailure=footingMinimumSteel({...x,spacing:.5});
assert.equal(spacingFailure.reason,'FOOTING_MAXIMUM_REINFORCEMENT_SPACING_EXCEEDED');
assert.deepEqual(spacingFailure.failedCriteria,['maximum-spacing']);
const both=footingMinimumSteel({...x,area:.001,spacing:.5});
assert.deepEqual(both.failedCriteria,['minimum-area','maximum-spacing']);
assert.equal(both.ratio,Math.max(...both.criteria.map(c=>c.ratio)));
const thick=footingMinimumSteel({...x,thickness:2});
assert.equal(thick.areaBasis.uncappedRequiredArea,.008);
assert.equal(thick.areaBasis.maximumRequiredArea,.0036);
assert.equal(thick.areaBasis.capApplied,true);
assert.equal(thick.areaBasis.capPerUnitWidth,.0018);
assert.equal(footingMinimumSteel(x).areaBasis.capApplied,false);
assert.equal(footingMinimumSteel({...x,fy:NaN}).status,'NOT_CHECKED');
assert.ok(both.criteria.every(c=>c.codeReferences.length&&c.unit));
console.log('PASS independent minimum-area/spacing diagnosis and dimensional cap trace');
