import assert from 'node:assert/strict';
import { createModel } from '../src/core/model.js';
import { stableHash } from '../src/core/stableHash.js';
import { createWorkflowInputIdentity, sameWorkflowInput, legacyIdentityDecision } from '../src/core/workflowIdentity.js';
import { createWorkflowResultStore } from '../src/compute/product/workflowResults.js';
import { createAnalysisRunRecord } from '../src/core/analysisRunRecord.js';
import { installResultViewCache } from '../src/ui/resultViewCache.js';

const model = createModel();
model.loadCombinations = [{id:'D1', factors:{D:1}}];
model.analysisCases = [{ id:'AC1', kind:'static', settings:{ comboId:'D1' } }];
const base = { model, analysisCase:model.analysisCases[0], build:{id:'test-build'}, rulePack:{id:'test-rules'} };
const identity = createWorkflowInputIdentity(base);
const clone = structuredClone(model);
Object.assign(clone.analysisCases[0], { status:'completed',lastRun:{at:'now'},staleReason:'derived' });
assert.equal(createWorkflowInputIdentity({...base,model:clone,analysisCase:clone.analysisCases[0]}).inputHash,identity.inputHash);
for (const patch of [ {settings:{tolerance:1e-5}}, {designSettings:{effectiveLength:2}}, {build:{id:'different'}}, {rulePack:{id:'changed'}}, {library:{sections:[{revision:2}]}} ]) {
  assert.equal(sameWorkflowInput(identity,createWorkflowInputIdentity({...base,...patch})),false);
}
assert.equal(sameWorkflowInput(identity,{...identity,modelHash:'0'.repeat(64)}),false);
assert.equal(legacyIdentityDecision(identity,{modelHash:'1'.repeat(16)}).compatible,false);
assert.throws(()=>createWorkflowInputIdentity({...base,settings:{x:NaN}}),/NONFINITE_INPUT/);
const ledger = createWorkflowResultStore();
const record = createAnalysisRunRecord({model,analysisCase:model.analysisCases[0],attemptId:'A1',result:{ok:true,status:'ok',payload:{summary:{displacement:1}}}});
const stored = ledger.recordAnalysis(record,identity);
assert.equal(stored.designTransferAllowed,false,'unqualified numerical success does not authorize design');
record.result.payload.summary.displacement=99;
assert.equal(ledger.getAnalysis('A1',identity).result.payload.summary.displacement,1);
const changed=createWorkflowInputIdentity({...base,designSettings:{effectiveLength:2}});
assert.equal(ledger.assertCurrent('A1',changed).code,'STALE_INPUT');
const sources=[{analysisRunId:'A1',comboId:'D1'}];
const currentIdentities={A1:identity};
const demandContract={kind:'elastic-static',units:model.units,axes:'member-local',signConvention:'solver-native',comboIds:['D1']};
const plan=ledger.planDesign({sources,currentIdentities,demandContract});
assert.equal(plan.ok,true);
assert.equal(ledger.planDesign({sources,currentIdentities,demandContract:{...demandContract,units:{}}}).code,'DESIGN_DEMAND_MAPPING_REQUIRED');
assert.equal(ledger.planDesign({sources,currentIdentities,demandContract:{...demandContract,units:{...model.units,force:'N'}}}).code,'DESIGN_DEMAND_UNITS_MISMATCH');
assert.equal(ledger.planDesign({sources:[{analysisRunId:'A1',comboId:'forged'}],currentIdentities,demandContract:{...demandContract,comboIds:['forged']}}).code,'COMBINATION_PROVENANCE_REQUIRED');
const design=ledger.recordDesign({identity,plan,currentIdentities,result:{members:[{id:'M1',status:'NG',ratio:1.2}]}});
assert.equal(design.designTransferAllowed,false);
assert.deepEqual(design.sourceAnalysisRunIds,['A1']);
assert.equal(ledger.getDesign(design.designRunId,changed).stale,true);
assert.throws(()=>ledger.recordDesign({identity,plan:{...plan,qualification:'verified'},currentIdentities,result:{}}),/DESIGN_PLAN_INVALID/);
assert.throws(()=>ledger.recordDesign({identity,plan,currentIdentities:{A1:changed},result:{}}),/STALE_INPUT/);
const nonlinear=createAnalysisRunRecord({model,analysisCase:{id:'NL',kind:'pushover'},attemptId:'NL',result:{ok:true,status:'ok',payload:{curve:[1,2]}}});
ledger.recordAnalysis(nonlinear,identity);
assert.equal(ledger.planDesign({sources:[{analysisRunId:'NL',comboId:'D1'}],currentIdentities:{NL:identity},demandContract}).code,'DESIGN_DEMAND_MAPPING_UNSUPPORTED');
let calls=0,current=identity;
const api={getDesign(){calls++;return {ratio:1.2};}};
installResultViewCache(api,['getDesign'],()=>current);
assert.equal(api.getDesign().code,'RESULT_REQUIRED');
assert.equal(calls,0);
api.prepareResultView('getDesign');
const result=api.getDesign();result.ratio=999;
assert.equal(api.getDesign().ratio,1.2);
assert.equal(calls,1);
current=changed;
assert.equal(api.getDesign().code,'STALE_INPUT');
assert.equal(calls,1);
console.log(JSON.stringify({ok:true,identity:identity.inputHash,resultHash:stableHash(design.result),independentStatuses:true,immutableRecords:true,staleGuard:true,queryComputationCount:0}));
