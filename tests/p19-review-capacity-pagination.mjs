import assert from 'node:assert/strict';
import {getNonlinearResultSlice} from '../src/nonlinear/product/resultAccess.js';
let visited=0;
const capacityCurve=Array.from({length:10000},(_,step)=>({step,get controlDisplacement(){visited++;return step/10000;},baseShear:step*2}));
const result={kind:'pushover',capacityCurve};
const page=getNonlinearResultSlice(result,{slice:'capacity',page:2,pageSize:20});
assert.equal(page.data.pointCount,10000);
assert.equal(page.data.points.length,20);
assert.equal(page.data.points[0].index,20);
assert.equal(page.data.points.at(-1).baseShear,78);
assert.equal(page.data.pagination.hasNext,true);
assert.ok(visited<=21,'A bounded request must not read every capacity point');
assert.ok(JSON.stringify(page).length<10000,'A large curve must fit one WebMCP response page');
const tail=getNonlinearResultSlice(result,{slice:'capacity',page:500,pageSize:20,index:9999});
assert.equal(tail.data.selected.index,9999);
assert.equal(tail.data.pagination.hasNext,false);
assert.equal(getNonlinearResultSlice(result,{slice:'capacity'}).data.points.length,10000,'Unpaginated native UI contract remains complete');
assert.equal(capacityCurve[20].baseShear,40);
console.log('PASS 10,000-step bounded capacity pages, global indices, final page and native full-curve compatibility');
