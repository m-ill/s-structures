import assert from 'node:assert/strict';
import {solveCrackedElasticSection} from '../src/design/rc/crackedElasticSection.js';
const B=.3,H=.5,Ec=10000,Es=200000,area=.0003;
const bars=[-.2,.2].flatMap(y=>[-.1,.1].map(z=>({y,z,area})));
const As=4*area,Ac=B*H-As,N=-500,concrete=-.0003,steel=0;
const input={B,H,Ec,Es,bars,demand:{N,My:0,Mz:0},includeBarForces:true,initialStrains:{concrete,steel}};
const expected=(N/1000+Ec*Ac*concrete+Es*As*steel)/(Ec*Ac+Es*As);
assert.ok(expected<concrete,'independent example keeps all concrete in compression');
const result=solveCrackedElasticSection(input);assert.equal(result.ok,true,JSON.stringify(result));
assert.ok(Math.abs(result.strain[0]-expected)<1e-12,JSON.stringify({actual:result.strain[0],expected}));
assert.ok(Math.abs(result.sectionComponents.steel.N-Es*As*1000*(expected-steel))<1e-8);
assert.ok(Math.abs(result.sectionComponents.concreteNet.N-Ec*Ac*1000*(expected-concrete))<1e-8);
assert.ok(Math.abs(result.recovered.N-N)<1e-8);
const common=solveCrackedElasticSection({...input,demand:{N:0,My:0,Mz:0},initialStrains:{concrete:.0001,steel:.0001}});
assert.equal(common.ok,true);assert.ok(Math.abs(common.strain[0]-.0001)<1e-12);assert.ok(common.steelForces.every(f=>Math.abs(f)<1e-8));
assert.equal(solveCrackedElasticSection({...input,initialStrains:{concrete:NaN,steel:0}}).ok,false);
const original=solveCrackedElasticSection({...input,initialStrains:undefined}),zero=solveCrackedElasticSection({...input,initialStrains:{concrete:0,steel:0}});
assert.deepEqual(original,zero);
const mixed=solveCrackedElasticSection({...input,demand:{N:-20,My:3,Mz:15}}),shift=.0002;
const shifted=solveCrackedElasticSection({...input,demand:{N:-20,My:3,Mz:15},initialStrains:{concrete:concrete+shift,steel:steel+shift}});
assert.equal(mixed.ok,true,JSON.stringify(mixed));assert.equal(shifted.ok,true,JSON.stringify(shifted));
assert.ok(Math.abs(shifted.strain[0]-mixed.strain[0]-shift)<1e-10);
for(const k of [1,2])assert.ok(Math.abs(shifted.strain[k]-mixed.strain[k])<1e-10);
assert.ok(Math.abs(shifted.compressionArea-mixed.compressionArea)<1e-10);
for(let i=0;i<bars.length;i++)assert.ok(Math.abs(shifted.steelForces[i]-mixed.steelForces[i])<1e-7);
assert.ok(mixed.compressionArea<B*H&&mixed.compressionArea>0,'partially compressed biaxial section');
console.log(JSON.stringify({expectedStrain:expected,recovered:result.recovered,steel:result.sectionComponents.steel,concreteNet:result.sectionComponents.concreteNet}));
console.log('PASS independent composite compression with differential initial strain, common free strain and zero-strain compatibility');
