import assert from 'node:assert/strict';
import { createModel } from '../src/core/model.js';
import { installIndexEngineBridge } from '../src/ui/indexBridge.js';
import { createWebMcpTools, webmcpModelHash } from '../src/ui/webmcp/tools.js';
import { installWebMcp } from '../src/ui/webmcp/register.js';
import { buildNativeIndexShell, createFakeIndexDocument } from './helpers/fakeIndexDom.mjs';

const model = createModel();
model.nodes = [{ id: 'N1', x: 0, y: 0, z: 0, support: 'fixed' }, { id: 'N2', x: 0, y: 0, z: 3 }];
model.members = [{ id: 'M1', type: 'frame', n1: 'N1', n2: 'N2', matId: 'steel', secId: 'h300', releases: { i: 'rigid', j: 'rigid' } }];
model.loadCases = [{ id: 'D', name: 'Dead', type: 'dead' }];
model.loadCombinations = [{ id: 'D1', name: 'Dead', type: 'service', factors: { D: 1 } }];
model.loads = [{ id: 'P1', type: 'nodal', node: 'N2', P: 10, dir: '-z', case: 'D' }];
model.analysisCases = [{ id: 'EL-STATIC', name: 'Static', kind: 'static', status: 'not-run', settings: { comboId: 'D1', pDeltaMethod: 'off' } }];
const document = createFakeIndexDocument();
buildNativeIndexShell(document);
let redraws = 0, synchronousAnalysis = 0;
const target = { document, model: () => model, location: { search: '' }, reanalyze() { synchronousAnalysis++; }, draw() { redraws++; }, getComputedStyle: (e) => ({ display: e.style?.display || 'block', visibility: 'visible' }) };
document.defaultView = target;
const bridge = installIndexEngineBridge(target);
const agent = target.SStructuresAgent;
await Promise.resolve();
const initialAnalysis = synchronousAnalysis;
assert.equal(target.SStructuresWebMcp.status, 'unsupported');
const tools = createWebMcpTools({ agent, bridge });
const call = (name, args = {}) => tools.find((row) => row.name === name).execute(args);
const before = JSON.stringify(model);
const ctx = await call('get_project_context');
await call('inspect_model');
assert.equal(JSON.stringify(model), before, 'read tools must not alter model');
assert.equal(bridge.listAnalysisRuns().length, 0, 'read tools must not schedule a solver');
assert.equal(synchronousAnalysis, initialAnalysis, 'read tools must not call the synchronous solver');
assert.equal(ctx.modelHash, webmcpModelHash(model));
const input = { caseId: 'EL-STATIC', modelHash: ctx.modelHash, computeTarget: 'cpu' };
const planned = await call('plan_analysis', input);
assert.equal(planned.plan.planHash, agent.planAnalysisRun({ caseId: 'EL-STATIC', computeTarget: 'cpu' }).planHash);
assert.equal((await call('validate_analysis', input)).validation.ok, true);
for (const invalid of [{ ...input, computeTarget: 'gup' }, { ...input, modelHash: 'old' }, { ...input, model: {} }]) {
  await assert.rejects(call('plan_analysis', invalid), { code: 'INVALID_INPUT' });
}
await assert.rejects(call('inspect_model', { limit: NaN }), { code: 'INVALID_INPUT' });
await assert.rejects(call('inspect_model', { limit: Infinity }), { code: 'INVALID_INPUT' });
await assert.rejects(call('plan_analysis', { ...input, caseId: 'missing' }), { code: 'CASE_NOT_FOUND' });
const blocked = await call('start_analysis', { ...input, computeTarget: 'gpu', requestId: 'gpu' });
assert.equal(blocked.status, 'blocked');
assert.equal(bridge.listAnalysisRuns().length, 0);
const job = await call('start_analysis', { ...input, requestId: 'one' });
const repeated = await call('start_analysis', { ...input, requestId: 'one' });
assert.equal(repeated.jobId, job.jobId);
assert.equal(repeated.reused, true);
await assert.rejects(call('start_analysis', { ...input, requestId: 'one', computeTarget: 'auto' }), { code: 'REQUEST_ID_CONFLICT' });
await bridge.getProductAnalysisService().wait(job.jobId);
const status = await call('get_analysis_status', { jobId: job.jobId });
assert.equal(status.status.status, 'completed');
assert.equal(status.stale, false, 'derived status/lastRun updates do not stale numerical inputs');
const result = await call('get_result_slice', { jobId: job.jobId });
assert.deepEqual(result.slice.data, agent.getAnalysisRunResult(job.jobId).summary);
assert.equal(result.slice.productProvenance.planHash, status.status.planHash);
assert.equal(result.externalQualification, 'NOT_CLAIMED');
await assert.rejects(call('get_result_slice', { jobId: job.jobId, path: 'payload.__proto__' }), { code: 'INVALID_PATH' });
await assert.rejects(call('get_result_slice', { jobId: job.jobId, path: 'payload.missing' }), { code: 'RESULT_PATH_NOT_FOUND' });
model.loads[0].P = 20;
assert.equal((await call('get_analysis_status', { jobId: job.jobId })).stale, true);
await assert.rejects(call('start_analysis', { ...input, requestId: 'stale' }), { code: 'STALE_MODEL' });
// New analysis uses a frozen input, not subsequent edits to the UI model.
const next = await call('start_analysis', { ...input, modelHash: webmcpModelHash(model), requestId: 'two' });
model.loads[0].P = 30;
await bridge.getProductAnalysisService().wait(next.jobId);
assert.equal((await call('get_analysis_status', { jobId: next.jobId })).stale, true);
assert.equal(bridge.listAnalysisRuns().length, 2);
await assert.rejects(call('get_analysis_status', { jobId: 'other-session' }), { code: 'JOB_NOT_FOUND' });

// Registration is nonblocking even if browser registration promises remain pending.
const registered = [];
let pagehide;
const supported = { SStructuresAgent: agent, document: { modelContext: { registerTool(tool) { registered.push(tool); return new Promise(() => {}); } } }, addEventListener(type, handler) { if (type === 'pagehide') pagehide = handler; } };
const registration = installWebMcp(supported, bridge);
assert.equal(registration.status, 'registered');
assert.equal(registered.length, 9);
assert.equal(installWebMcp(supported, bridge), registration);
pagehide({ persisted: true });
assert.equal(registration.status, 'registered');
pagehide({ persisted: false });
assert.throws(() => registered[0].execute({}), /inactive/);
const framed = { ...supported, SStructuresWebMcp: undefined, top: {} };
assert.equal(installWebMcp(framed, bridge).status, 'top-level-required');
const rejected = { SStructuresAgent: agent, document: { modelContext: { registerTool() { return Promise.reject(new Error('disabled')); } } } };
installWebMcp(rejected, bridge);
await Promise.resolve();
assert.equal(rejected.SStructuresWebMcp.status, 'registration-failed');
console.log(JSON.stringify({ ok: true, toolCount: tools.length, actualSolverJobs: bridge.listAnalysisRuns().length, planParity: true, resultParity: true, staleGuard: true, duplicateGuard: true, registrationFallback: true }));
