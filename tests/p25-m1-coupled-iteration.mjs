import assert from 'node:assert/strict';
import {createCantileverTipLoad} from '../src/index.js';
import {stableHash} from '../src/core/stableHash.js';
import {workflowModelInput} from '../src/core/workflowIdentity.js';
import {prepareFlexuralAnalysisModel} from '../src/compute/product/flexuralAnalysisProfile.js';
import {runFlexuralIteration} from '../src/compute/product/flexuralIteration.js';
const m=createCantileverTipLoad().model,member=m.members[0];
m.loads=[{id:'axial',type:'nodal',node:member.n2,P:10,dir:'+x',case:'D'}];
m.loadCombinations.push({...structuredClone(m.loadCombinations[0]),id:'OTHER',factors:{D:2}});
const before=stableHash(m),sourceModelHash=stableHash(workflowModelInput(m));
const C=[[2e-6,3e-6,-2e-6],[3e-6,2e-4,4e-5],[-2e-6,4e-5,1e-4]];
const profiles=[{memberId:member.id,segments:[{start:0,end:1,axialBendingFlexibility:C}]}];
const projected=prepareFlexuralAnalysisModel(m,{sourceModelHash,profiles});
assert.deepEqual(projected.model.sections.at(-1).properties.axialBendingFlexibility,C);
assert.equal(stableHash(m),before);
const copy=structuredClone(profiles);copy[0].segments[0].axialBendingFlexibility[1][1]*=2;
assert.notEqual(prepareFlexuralAnalysisModel(m,{sourceModelHash,profiles:copy}).profileHash,projected.profileHash);
const invalid=structuredClone(profiles);invalid[0].segments[0].axialBendingFlexibility[0][1]=1;
assert.throws(()=>prepareFlexuralAnalysisModel(m,{sourceModelHash,profiles:invalid}),/FLEXURAL_PROFILE_COMPLIANCE/);
let calls=0;
const result=await runFlexuralIteration(m,{comboId:'D_ONLY',calculateProfiles:({analysis})=>{assert.deepEqual(Object.keys(analysis.byCombo),['D_ONLY']);calls++;return {profiles};}});
assert.equal(result.ok,true,JSON.stringify(result));assert.ok(calls>=3);
assert.deepEqual(result.profiles[0].segments[0].axialBendingFlexibility,C);
const d=result.analysis.byCombo.D_ONLY.memberResults[member.id].dl.slice(6),e=C.map(r=>r[0]*10),L=4;
[L*e[0],L*L*e[2]/2,L*L*e[1]/2,0,-L*e[1],L*e[2]].forEach((x,i)=>assert.ok(Math.abs(x-d[i])<1e-12));
const absent=await runFlexuralIteration(m,{comboId:'MISSING',calculateProfiles:()=>({profiles})});
assert.equal(absent.reason,'FLEXURAL_ITERATION_COMBINATION_REQUIRED');assert.equal(absent.analysis,undefined);
// Change an unloaded flexural axis: displacement alone cannot detect this cycle.
const cycling=await runFlexuralIteration(m,{comboId:'D_ONLY',maxIterations:4,calculateProfiles:({iteration})=>({profiles:[{memberId:member.id,segments:[{start:0,end:1,axialBendingFlexibility:[[2e-6,0,0],[0,iteration%2?2e-4:4e-4,0],[0,0,1e-4]]}]}]})});
assert.equal(cycling.converged,false);assert.equal(cycling.reason,'FLEXURAL_ITERATION_LIMIT');assert.equal(cycling.analysis,undefined);
assert.ok(cycling.trace.at(-1).profileResidual>.1);
assert.equal(stableHash(m),before);
console.log('PASS coupled projection, combination isolation, full matrix convergence and actual frame displacement');
