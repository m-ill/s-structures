import assert from 'node:assert/strict';
import {kdsStressBlock,evaluateKdsSection} from '../src/design/rc/kdsStrength.js';
import {parabolicConcreteResponse} from '../src/design/rc/parabolicConcrete.js';
const fc=55,law=kdsStressBlock(fc),B=.4,H=.6,c=.25;
assert.equal(law.kind,'parabolic-linear');assert.equal(law.epsco,.00215);assert.equal(law.epscu,.00315);
const r=law.epsco/law.epscu,n=law.exponent,f=.85*fc*B*c*1000*(1-r/(n+1));
const first=.85*fc*B*c*c*1000*(.5-r/(n+1)+r*r/((n+1)*(n+2)));
const result=parabolicConcreteResponse({B,H},fc,law,0,c);
assert.ok(Math.abs(result.N+f)/f<1e-5);
assert.ok(Math.abs(result.Mz-(-f*H/2+first))/Math.abs(result.Mz)<1e-5);
const rotated=parabolicConcreteResponse({B:H,H:B},fc,law,Math.PI/2,c);
assert.ok(Math.abs(rotated.N-result.N)<1e-8);assert.ok(Math.abs(rotated.My+result.Mz)<1e-8);
assert.equal(kdsStressBlock(91),null);assert.equal(kdsStressBlock(50).kind,undefined);
const bars=[-1,1].flatMap(y=>[-1,1].map(z=>({y:y*.23,z:z*.13,area:.0005,diameter:.025})));
const capacity=evaluateKdsSection({B,H},bars,{fc,fy:400,Es:200000},{N:-100,My:0,Mz:10});
assert.ok(['OK','NG'].includes(capacity.status),JSON.stringify(capacity));
assert.ok(capacity.codeReferences.find(x=>x.id==='142020').clause.includes('Eq.4.1-3'));
assert.ok(Math.abs(capacity.equilibrium.N+100)<1e-3);
console.log('PASS explicit intermediate-strength law, independent integrated resultant/centroid, axis rotation and section equilibrium');
