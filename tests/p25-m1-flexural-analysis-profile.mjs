import assert from 'node:assert/strict';
import {prepareFlexuralAnalysisModel} from '../src/compute/product/flexuralAnalysisProfile.js';
import {createCantileverTipLoad,analyzeModel} from '../src/index.js';
import {sectionOf,materialOf} from '../src/core/catalogs.js';
import {stableHash} from '../src/core/stableHash.js';
import {workflowModelInput} from '../src/core/workflowIdentity.js';
const m=createCantileverTipLoad().model,member=m.members[0],sec=sectionOf(m,member.secId);
const before=stableHash(m),hash=stableHash(workflowModelInput(m));
const profiles=[{memberId:member.id,segments:[{start:0,end:.2,Iy:sec.Iy/2,Iz:sec.Iz/2},{start:.2,end:1,Iy:sec.Iy,Iz:sec.Iz}]}];
const prepared=prepareFlexuralAnalysisModel(m,{sourceModelHash:hash,profiles});
assert.equal(stableHash(m),before);
assert.equal(prepared.model.members[0].secId,member.secId);
assert.deepEqual(prepared.model.designDetails,m.designDetails);
const run=analyzeModel(prepared.model).byCombo.D_ONLY;
assert.equal(run.ok,true);
const L=run.memberResults[member.id].L,E=materialOf(m,member.matId).E,P=Math.abs(m.loads[0].P);
const expected=P*L**3/(3*E*sec.Iz)*(2*(1-.8**3)+.8**3);
assert.ok(Math.abs(Math.abs(run.disp[member.n2][2])-expected)<expected*1e-12);
assert.ok(prepared.model.sections.length>m.sections.length);
assert.equal(prepared.sourceModelHash,hash);
const changed=structuredClone(m);changed.loads[0].P*=2;
assert.throws(()=>prepareFlexuralAnalysisModel(changed,{sourceModelHash:hash,profiles}),/STALE_FLEXURAL_PROFILE/);
const gap=structuredClone(profiles);gap[0].segments[1].start=.21;
assert.throws(()=>prepareFlexuralAnalysisModel(m,{sourceModelHash:hash,profiles:gap}),/FLEXURAL_PROFILE_COVERAGE/);
assert.throws(()=>prepareFlexuralAnalysisModel(m,{sourceModelHash:hash,profiles:[...profiles,...profiles]}),/DUPLICATE_FLEXURAL_PROFILE/);
const bad=structuredClone(profiles);bad[0].segments[0].Iz=NaN;
assert.throws(()=>prepareFlexuralAnalysisModel(m,{sourceModelHash:hash,profiles:bad}),/FLEXURAL_PROFILE_INERTIA/);
const twice=prepareFlexuralAnalysisModel(m,{sourceModelHash:hash,profiles});
assert.equal(stableHash(twice),stableHash(prepared));
console.log('PASS source-bound flexural profile, immutable source, deterministic projection and real frame stiffness');
