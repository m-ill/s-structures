import assert from 'node:assert/strict';
import { createModel } from '../src/core/model.js';
import { installIndexEngineBridge } from '../src/ui/indexBridge.js';
import { installIndexRuntimeAdapter } from '../src/ui/indexRuntimeAdapter.js';
import { createProductBook, extractProductModel } from '../src/ui/indexNativePersistence.js';
import { createFakeIndexDocument, buildNativeIndexShell } from './helpers/fakeIndexDom.mjs';
import { createIndexStartupSampleModel } from '../src/examples/indexStartupSample.js';
import { createPersistenceClient } from '../src/app/persistenceClient.js';
const doc=createFakeIndexDocument();buildNativeIndexShell(doc);
let model=createModel();
const target={document:doc,model:()=>model,location:{search:''},draw(){}};doc.defaultView=target;
const bridge=installIndexEngineBridge(target),workflow=bridge.elasticSetupWorkflow;
model.designBasis={...model.designBasis,deadLoad:8,liveLoad:2.5,region:'central',soil:'S4',importance:1.2,accidentalEccentricityRatio:0.07};
let before=structuredClone(model),identity=bridge.getWorkflowInputIdentity();
workflow.open(0);
assert.equal(workflow.state.draft.deadLoad,8);assert.equal(workflow.state.draft.soil,'S4');
for(let i=0;i<7;i++)workflow.go(i);
workflow.close();
assert.deepEqual(model,before);assert.deepEqual(bridge.getWorkflowInputIdentity(),identity);
workflow.open(1);doc.getElementById('ssEwDead').value='9';workflow.close();
model.designBasis.deadLoad=10;
before=structuredClone(model);workflow.open(0);workflow.applyBasis();
assert.equal(workflow.state.messageKind,'error');assert.match(workflow.state.message,/DRAFT_INPUT_CONFLICT/);
assert.deepEqual(model,before);assert.equal(workflow.state.draft.deadLoad,9);
workflow.reloadDraft();assert.equal(workflow.state.draft.deadLoad,10);
workflow.go(1);doc.getElementById('ssEwDead').value='11';workflow.applyBasis();
assert.equal(model.designBasis.deadLoad,11);assert.equal(model.designBasis.soil,'S4');assert.equal(model.designBasis.importance,1.2);
assert.deepEqual(model.loads,before.loads);assert.notEqual(bridge.getWorkflowInputIdentity().inputHash,identity.inputHash);
const afterApply=structuredClone(model);workflow.go(2);workflow.previewCombinations();assert.deepEqual(model,afterApply);

// Exercise the installed import routing boundary: envelope v1 must never reach the legacy v1 converter.
