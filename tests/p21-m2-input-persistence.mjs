const host={model:()=>fixture,migrateToV3:x=>{legacyConversions++;return {...x,schemaVersion:3,analysisSettings:{includeShearDeformation:false,...x.analysisSettings}};},loadBookData:x=>{routed=x;}};
installIndexRuntimeAdapter(host);
const book=createProductBook(fixture),original=structuredClone(book);
host.loadBookData(book);
assert.equal(routed.version,3);assert.equal(legacyConversions,0);assert.equal(routed.pages[0].model.schemaVersion,6);
assert.deepEqual(book,original);assert.equal(routed.pages[0].model.analysisSettings.shearDeformation,true);
assert.equal(Object.hasOwn(routed.pages[0].model.analysisSettings,'includeShearDeformation'),false);
assert.deepEqual(extractProductModel(createProductBook(extractProductModel(book))),extractProductModel(book));
assert.throws(()=>host.loadBookData({...book,version:99}),/VERSION_UNSUPPORTED/);
const tampered=structuredClone(book);tampered.pages[0].model.nodes[0].z+=1;
assert.throws(()=>host.loadBookData(tampered),e=>e.code==='PRODUCT_MODEL_SIGNATURE_MISMATCH');
const conflicting=structuredClone(fixture);conflicting.analysisSettings.includeShearDeformation=false;
assert.throws(()=>createProductBook(conflicting));
let saved;
const client=createPersistenceClient({post:async(path,{body})=>{saved=body.model;return {revision:{rev:1}};},get:async()=>({model:saved})});
await client.saveToServer('test',fixture);assert.equal(saved.schemaVersion,6);assert.deepEqual((await client.loadFromServer('test',1)).model,saved);
